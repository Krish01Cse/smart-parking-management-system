-- 1. Users Table (Stores user & admin credentials with PBKDF2 salted hash)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'Customer',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 2. Parking Slots Table
CREATE TABLE IF NOT EXISTS public.parking_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_number TEXT UNIQUE NOT NULL,
    vehicle_type TEXT NOT NULL DEFAULT 'Car',
    location_zone TEXT NOT NULL,
    hourly_rate NUMERIC(10, 2) NOT NULL DEFAULT 5.00,
    status TEXT NOT NULL DEFAULT 'Available',
    current_vehicle TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 3. Reservations / Bookings Table
CREATE TABLE IF NOT EXISTS public.reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id TEXT UNIQUE NOT NULL,
    slot_id BIGINT REFERENCES public.parking_slots(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL,
    customer_email TEXT,
    customer_phone TEXT,
    vehicle_reg_number TEXT NOT NULL,
    vehicle_type TEXT NOT NULL DEFAULT 'Car',
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    duration_hours NUMERIC(10, 2) NOT NULL DEFAULT 1.0,
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 5.00,
    status TEXT NOT NULL DEFAULT 'Confirmed',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 4. Payments Table (Receipts)
CREATE TABLE IF NOT EXISTS public.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id TEXT UNIQUE NOT NULL,
    reservation_id BIGINT REFERENCES public.reservations(id) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL,
    hourly_rate NUMERIC(10, 2) NOT NULL,
    duration_hours NUMERIC(10, 2) NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'Razorpay Gateway',
    status TEXT NOT NULL DEFAULT 'Paid',
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 5. QA Test Cases Table
CREATE TABLE IF NOT EXISTS public.test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_case_id TEXT UNIQUE NOT NULL,
    module TEXT NOT NULL,
    test_scenario TEXT NOT NULL,
    test_data TEXT,
    expected_result TEXT,
    actual_result TEXT,
    status TEXT NOT NULL DEFAULT 'Passed',
    test_type TEXT DEFAULT 'Functional',
    executed_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 6. Defects / Bugs Table
CREATE TABLE IF NOT EXISTS public.defects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bug_id TEXT UNIQUE NOT NULL,
    bug_description TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT 'Medium',
    status TEXT NOT NULL DEFAULT 'Open',
    assigned_to TEXT,
    reported_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- ====================================================================
-- DEDICATED CONVENIENCE VIEWS FOR SUPABASE TABLE EDITOR
-- These provide immediate named access for bookings, admin logins,
-- user logins, and credentials
-- ====================================================================

-- Dedicated "bookings" view
CREATE OR REPLACE VIEW public.bookings AS
SELECT 
    id,
    booking_id,
    slot_id,
    user_id,
    customer_name,
    customer_email,
    customer_phone,
    vehicle_reg_number,
    vehicle_type,
    start_time,
    end_time,
    duration_hours,
    total_amount,
    status,
    created_at
FROM public.reservations;

-- Dedicated "admin_logins" view (Filters only users with Administrator privileges)
CREATE OR REPLACE VIEW public.admin_logins AS
SELECT 
    id,
    name AS admin_name,
    email AS admin_email,
    phone AS admin_phone,
    role,
    password_hash,
    created_at
FROM public.users
WHERE role = 'Administrator';

-- Dedicated "user_logins" view (Filters Customer / User accounts)
CREATE OR REPLACE VIEW public.user_logins AS
SELECT 
    id,
    name AS customer_name,
    email AS customer_email,
    phone AS customer_phone,
    role,
    password_hash,
    created_at
FROM public.users
WHERE role = 'Customer';

-- Dedicated "user_credentials" view (Complete credential directory)
CREATE OR REPLACE VIEW public.user_credentials AS
SELECT 
    id,
    name,
    email,
    phone,
    role,
    password_hash,
    created_at
FROM public.users;

